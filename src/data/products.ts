export function getCatalogProduct(slug: string): CatalogProduct | undefined {
  return catalogProducts.find((product) => product.slug === slug);
}

export function getCustomProduct(slug: string): CatalogProduct | undefined {
  return customProducts.find((product) => product.slug === slug);
}

export function getCatalogByCategory(category: string): CatalogProduct[] {
  return catalogProducts.filter((product) => product.category === category);
}

export function getCustomByCategory(category: string): CatalogProduct[] {
  return customProducts.filter((product) => product.category === category);
}

export function getCustomBySubcategory(subcategory: string): CatalogProduct[] {
  return customProducts.filter((product) => product.subcategory === subcategory);
}

export function getFeaturedCatalog(count = 4): CatalogProduct[] {
  return customProducts.slice(0, count);
}

export function getCatalogRelated(articleCategorySlug: string, count = 4): CatalogProduct[] {
  const mapping: Record<string, string[]> = {
    watches: ["Watches"],
    sunglasses: ["Sunglasses"],
    streetwear: ["Wristbands", "Bracelets"],
    accessories: ["Wristbands", "Bracelets", "Wallets", "Bags", "Keychains"],
    style: ["Watches", "Sunglasses"],
    trends: ["Watches", "Sunglasses", "Wristbands"],
  };
  const cats = mapping[articleCategorySlug] ?? ["Watches", "Sunglasses"];
  const matched = catalogProducts.filter((product) => cats.includes(product.category));
  const pool = matched.length > 0 ? matched : catalogProducts;
  return pool.slice(0, count);
}

export function getAllProducts(): CatalogProduct[] {
  return [...customProducts, ...catalogProducts];
}

